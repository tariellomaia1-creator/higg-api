/** `---`-separated text → variants (empty blocks dropped). */
export function parseVariants(text: string): string[] {
  return text
    .split(/^\s*---\s*$/m)
    .map((block) => block.trim().slice(0, 2200))
    .filter(Boolean)
}

export function formatVariants(variants: string[]): string {
  return variants.join("\n---\n")
}
